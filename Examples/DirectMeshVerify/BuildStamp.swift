// BuildStamp.swift
// Regenerated before every build by the "Stamp build info" script phase in project.yml, which
// overwrites this file's content with the current git SHA + timestamp. Tracked (not gitignored)
// so a fresh checkout has something for xcodegen to see before the script has ever run — xcodegen
// scans this directory once, at generation time, so a gitignored file wouldn't exist yet on a
// clean clone and would never be added as a source. Expect `git status` to show this file as
// locally modified after every on-device build; that's the mechanism working as intended.

enum BuildStamp {
    static let value = "unstamped-build"
}
